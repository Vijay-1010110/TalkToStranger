/**
 * Detect language from browser navigator or saved user preference
 */
export function detectInitialLanguage() {
  if (typeof window === 'undefined') return 'en';

  let saved = null;
  try {
    saved = localStorage.getItem('stranger_user_lang');
  } catch (e) {}
  if (saved && TRANSLATIONS[saved]) return saved;

  const browserLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  
  // Try exact 2-letter match (e.g. 'es', 'fr', 'hi')
  const primary = browserLang.split('-')[0];
  if (TRANSLATIONS[primary]) {
    return primary;
  }

  return 'en';
}
